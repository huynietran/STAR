#!/usr/bin/env python3
"""Convert a tracked turtle's positions (and a coastline) into OLED pixel arrays.

Input CSV columns: day,lat,lon   (latitude north positive, longitude west negative)
Example row:       14,28.8,-94.9

Run:
    python3 tools/journey_to_progmem.py track.csv coast.csv > turtle_board/journey_data.h

coast.csv uses the same columns; its "day" column is ignored.
Both files are mapped with the same bounds so the dot lines up with the coast.
Edit BOUNDS below to frame your map (default: Tamaulipas to Alabama).
"""
import csv
import sys

# lon_min, lon_max, lat_min, lat_max  (degrees)
BOUNDS = (-98.5, -88.0, 22.0, 31.0)
W, H = 128, 64


def to_xy(lat, lon):
    lon_min, lon_max, lat_min, lat_max = BOUNDS
    x = round((lon - lon_min) / (lon_max - lon_min) * (W - 1))
    y = round((lat_max - lat) / (lat_max - lat_min) * (H - 1))
    return max(0, min(W - 1, x)), max(0, min(H - 1, y))


def read(path):
    with open(path, newline="") as f:
        return [(int(float(r["day"])), float(r["lat"]), float(r["lon"]))
                for r in csv.DictReader(f)]


def emit(name, pts, with_days):
    print(f"const uint8_t {name}_N = {len(pts)};")
    print(f"const uint8_t {name}_XY[][2] PROGMEM = {{")
    for _, lat, lon in pts:
        x, y = to_xy(lat, lon)
        print(f"  {{{x}, {y}}},")
    print("};")
    if with_days:
        print(f"const uint16_t {name}_DAY[] PROGMEM = {{"
              + ", ".join(str(d) for d, _, _ in pts) + "};")


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: journey_to_progmem.py track.csv coast.csv")
    print("// Generated by tools/journey_to_progmem.py -- do not edit by hand.")
    print(f"// Bounds lon {BOUNDS[0]}..{BOUNDS[1]}, lat {BOUNDS[2]}..{BOUNDS[3]}")
    print("#pragma once")
    print("#include <Arduino.h>")
    emit("TRACK", read(sys.argv[1]), True)
    emit("COAST", read(sys.argv[2]), False)


if __name__ == "__main__":
    main()
